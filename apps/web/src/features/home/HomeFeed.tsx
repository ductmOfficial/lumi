import { usePreferences } from "@/stores/preferences";
import { useCallback, useMemo, useState } from "react";
import { useQuery } from "@tanstack/react-query";
import {
  normalizeTvSummary,
  tmdbFetch,
  type MovieSummary,
  type Paginated,
  type RawTvSummary,
} from "@/lib/tmdb";
import { useTmdbLocale } from "@/stores/preferences";
import { useGenres } from "@/features/discover/api/queries";
import { assignLayouts, buildRows, type FeedScope } from "@/features/personalization/engine";
import { usePersonalization } from "@/features/personalization/store";
import { HomeRow } from "@/features/personalization/components/HomeRow";
import { HeroCarousel } from "@/features/personalization/components/HeroCarousel";
import { Onboarding } from "@/features/personalization/components/Onboarding";
import { themeBySlug } from "@/features/discover/catalog";
import { UpNextRow } from "@/features/library/components/UpNextRow";

/** Rows loaded immediately; the rest load only when scrolled into view. */
const EAGER_ROWS = 3;
const NONE_CLAIMED: ReadonlySet<string> = new Set();

type TrendingItem =
  | (MovieSummary & { media_type: "movie" })
  | (RawTvSummary & { media_type: "tv" })
  | { media_type: "person" };

/** Candidates for the large banner, per page scope. */
function useHeroCandidates(scope: FeedScope) {
  const { language } = useTmdbLocale();
  return useQuery({
    queryKey: ["hero", scope, language],
    queryFn: async ({ signal }): Promise<MovieSummary[]> => {
      const path =
        scope === "movie"
          ? "/trending/movie/week"
          : scope === "tv"
            ? "/trending/tv/week"
            : "/trending/all/week";
      const page = await tmdbFetch<Paginated<TrendingItem>>(path, { language }, signal);
      return page.results.flatMap((r): MovieSummary[] => {
        const type = scope === "all" ? r.media_type : scope;
        if (type === "tv") return [normalizeTvSummary(r as RawTvSummary)];
        if (type === "movie") return [{ ...(r as MovieSummary), media_type: undefined }];
        return [];
      });
    },
  });
}

function passiveSignals() {
  const { events, history } = usePersonalization.getState();
  return { events, history };
}

/**
 * Streaming-style layout shared by Home (all types), Movies and Series:
 * banner + personalized rows generated by the engine for the scope.
 */
export function HomeFeed({ scope }: { scope: FeedScope }) {
  const hero = useHeroCandidates(scope);
  const genres = useGenres(scope === "tv" ? "tv" : "movie");
  // Passive signals (events, history) are snapshotted on page entry: playing a trailer / opening a card on the page
  // does not reshuffle the rows (or interrupt a playing video). Finishing onboarding takes a new snapshot.
  const onboardingStatus = usePersonalization((s) => s.onboarding.status);
  const [snap, setSnap] = useState(passiveSignals);
  const [snapFor, setSnapFor] = useState(onboardingStatus);
  if (snapFor !== onboardingStatus) {
    setSnapFor(onboardingStatus);
    setSnap(passiveSignals());
  }
  const { events, history } = snap;
  const watchlist = usePersonalization((s) => s.watchlist);
  const reactions = usePersonalization((s) => s.reactions);
  const topics = usePersonalization((s) => s.topics);
  const streaming = usePreferences((s) => s.streamingService);

  // Pin the time on page entry so the row list does not keep jumping
  const [now] = useState(() => new Date());
  const rows = useMemo(
    () =>
      buildRows(
        { events, history, watchlist, reactions },
        {
          now,
          scope,
          allGenreIds: (genres.data ?? []).map((g) => g.id),
          followedTopics: topics.flatMap((slug) => {
            const theme = themeBySlug(slug);
            return theme ? [{ slug, media: theme.media }] : [];
          }),
          streaming,
        },
      ),
    [events, history, watchlist, reactions, topics, streaming, now, scope, genres.data],
  );

  const layouts = useMemo(() => assignLayouts(rows), [rows]);

  // Avoid repeating titles across rows: each row "claims" its list of keys
  const [claims, setClaims] = useState<Record<number, string[]>>({});
  const onClaim = useCallback((index: number, keys: string[]) => {
    setClaims((prev) => (prev[index]?.join() === keys.join() ? prev : { ...prev, [index]: keys }));
  }, []);
  const claimedAbove = useMemo(() => {
    // one set per row: the titles already shown by the rows above it
    const result: Set<string>[] = [];
    const acc = new Set<string>();
    rows.forEach((_, i) => {
      result.push(new Set(acc));
      claims[i]?.forEach((k) => acc.add(k));
    });
    return result;
  }, [rows, claims]);

  return (
    <>
      {scope === "all" && <Onboarding />}
      <HeroCarousel candidates={hero.data} />
      <div className="mx-auto max-w-app space-y-5 px-4 py-4 sm:space-y-10 sm:px-6 sm:py-8">
        {/* series being watched episode by episode → next episode */}
        {scope !== "movie" && <UpNextRow />}
        {rows.map((spec, i) => (
          <HomeRow
            key={spec.id}
            spec={spec}
            index={i}
            eager={i < EAGER_ROWS}
            claimedAbove={claimedAbove[i] ?? NONE_CLAIMED}
            onClaim={onClaim}
            layout={layouts[spec.id]}
          />
        ))}
      </div>
    </>
  );
}
